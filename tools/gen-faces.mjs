#!/usr/bin/env node
/* Generate the flat face textures that wrap onto each driver's 3D head, using the
   approved portraits as likeness references. Writes assets/faces/<id>.webp (with a
   soft round alpha edge) and src/content/faces.js (sampled skin tones).
   Usage: node tools/gen-faces.mjs [id ...] [--force] */
import { mkdir, writeFile, readFile, access } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { generateImage } from './gen-image.mjs';
import { RACERS } from '../src/content/racers.js';

const PROMPT = who => `Create a flat, front-facing FACE TEXTURE for a 3D bobblehead video game character, based on ${who} in the reference image. Show only the face: forehead, eyebrows, eyes, nose, cheeks, mouth, and chin, viewed exactly from the front, symmetrical and centered. The eyes sit slightly above the middle of the image and the face fills the central 70 percent of the square. Keep eyeglasses, moustache or beard if the reference character has them, drawn flat on the face. No hair on top, no ears, no neck, no shoulders, no clothing, no hat. Everything outside the face, out to all four edges, is the same flat skin color as the face, and the edge of the face blends smoothly into it: no outline of the head, no jawline shadow, no dark vignette, no background. Style: charming stylized 3D-animated-film caricature with large expressive eyes and smooth simplified skin (no pores, minimal wrinkles), soft even shadowless lighting, keeping the same recognizable likeness as the reference. Friendly, confident, slightly smug expression.`;

const args = process.argv.slice(2), force = args.includes('--force'), only = args.filter(a => !a.startsWith('--'));
const jobs = [];
for (const r of RACERS) {
  if (r.look.duo) {
    jobs.push({ id: r.id, ref: r.portrait, who: 'the older man on the LEFT (grey hair, glasses)' });
    jobs.push({ id: r.id + '2', ref: r.portrait, who: 'the man on the RIGHT (dark curly hair, wearing a cap)' });
  } else jobs.push({ id: r.id, ref: r.portrait, who: 'the caricature' });
}
const todo = jobs.filter(j => !only.length || only.includes(j.id));
await mkdir('assets/faces', { recursive: true });
const tmp = join(tmpdir(), 'bk-faces-' + process.pid); await mkdir(tmp, { recursive: true });
const exists = p => access(p).then(() => true, () => false);

async function one(j) {
  const out = `assets/faces/${j.id}.webp`;
  if (!force && await exists(out)) return 'kept';
  const ref = join(tmp, j.id + '-ref.png'), raw = join(tmp, j.id + '-raw.png');
  execFileSync('magick', [j.ref, ref]);
  await generateImage({ prompt: PROMPT(j.who), out: raw, refs: [ref], size: '1024x1024', quality: 'high' });
  // soft round alpha so the face melts into the head colour
  execFileSync('magick', [raw, '-resize', '512x512', '(', '-size', '512x512', 'radial-gradient:white-black', '-level', '10%,40%', ')', '-alpha', 'off', '-compose', 'CopyOpacity', '-composite', '-quality', '90', out]);
  return 'made';
}
function skinOf(id) {
  // average of both cheeks
  const px = execFileSync('magick', [`assets/faces/${id}.webp`, '-alpha', 'off', '(', '+clone', '-crop', '40x40+140+300', '+repage', ')', '(', '-clone', '0', '-crop', '40x40+332+300', '+repage', ')', '-delete', '0', '+append', '-resize', '1x1!', '-format', '%[hex:p{0,0}]', 'info:']).toString().trim();
  return '#' + px.slice(0, 6).toLowerCase();
}

let i = 0; const results = {};
await Promise.all(Array.from({ length: 4 }, async () => {
  while (i < todo.length) {
    const j = todo[i++];
    try { results[j.id] = await one(j); console.log(j.id, results[j.id]); }
    catch (e) { results[j.id] = 'FAILED: ' + e.message; console.log(j.id, results[j.id]); }
  }
}));
const faces = {};
for (const j of jobs) if (await exists(`assets/faces/${j.id}.webp`)) faces[j.id] = { img: `assets/faces/${j.id}.webp`, skin: skinOf(j.id) };
await writeFile('src/content/faces.js', `/* Generated by tools/gen-faces.mjs. Face textures and the skin tone sampled from each. */\nexport const FACES = ${JSON.stringify(faces, null, 2)};\n`);
console.log('wrote src/content/faces.js with', Object.keys(faces).length, 'faces');
